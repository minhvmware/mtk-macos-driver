#!/usr/bin/env python3
"""
MT7902 Firmware Packager for macOS Kexts (AirportMT7902 + MT7902BluetoothFirmware).

Auto-discovers MediaTek MT7902 firmware binaries (supporting raw .bin and .bin.xz),
validates Connac2 Wi-Fi patch/RAM headers and btmtk 79xx BT section maps,
compresses each payload with zlib level 9, and emits C++ source tables for
embedding into the macOS kernel extensions (similar to AirportItlwm).
"""

import argparse
import lzma
import os
import struct
import sys
import zlib
from pathlib import Path

WIFI_PATCH_NAME = "WIFI_MT7902_patch_mcu_1_1_hdr.bin"
WIFI_RAM_NAME = "WIFI_RAM_CODE_MT7902_1.bin"
BT_RAM_NAME = "BT_RAM_CODE_MT7902_1_1_hdr.bin"


def read_firmware_file(fw_dir: Path, filename: str) -> bytes:
    raw_path = fw_dir / filename
    xz_path = fw_dir / f"{filename}.xz"
    if raw_path.is_file():
        return raw_path.read_bytes()
    if xz_path.is_file():
        return lzma.decompress(xz_path.read_bytes())
    raise FileNotFoundError(
        f"Missing firmware '{filename}' (or '{filename}.xz') in {fw_dir}"
    )


def validate_wifi_patch(data: bytes) -> str:
    # struct mt76_connac2_patch_hdr = 32 + 64 = 96 bytes
    if len(data) < 96:
        raise ValueError(f"Wi-Fi patch too short ({len(data)} bytes)")
    build_date = data[0:16].decode("ascii", errors="replace").strip("\x00\n ")
    platform = data[16:20].decode("ascii", errors="replace")
    hw_sw_ver, _patch_ver = struct.unpack_from(">II", data, 20)
    n_region = struct.unpack_from(">I", data, 32 + 12)[0]
    if n_region == 0 or len(data) < 96 + n_region * 64:
        raise ValueError(f"Invalid Wi-Fi patch n_region={n_region}")
    for i in range(n_region):
        off = 96 + i * 64
        sec_type, sec_offs, sec_size, addr, sec_len = struct.unpack_from(
            ">IIIII", data, off
        )
        if (sec_type & 0xFFFF) != 0x2:
            raise ValueError(f"Unexpected patch section {i} type=0x{sec_type:x}")
        if sec_offs + sec_len > len(data):
            raise ValueError(
                f"Patch section {i} out of bounds (offs={sec_offs}, len={sec_len})"
            )
    return f"platform={platform} hw_sw=0x{hw_sw_ver:08x} build={build_date} regions={n_region}"


def validate_wifi_ram(data: bytes) -> str:
    # struct mt76_connac2_fw_trailer = 36 bytes at tail, each region = 40 bytes
    if len(data) < 36:
        raise ValueError(f"Wi-Fi RAM firmware too short ({len(data)} bytes)")
    trailer_off = len(data) - 36
    chip_id, eco_code, n_region, fmt_ver, fmt_flag = struct.unpack_from(
        "<BBBBB", data, trailer_off
    )
    fw_ver = data[trailer_off + 7 : trailer_off + 17].decode("ascii", errors="replace").strip("\x00 ")
    build_date = data[trailer_off + 17 : trailer_off + 32].decode("ascii", errors="replace").strip("\x00 ")
    if n_region == 0 or len(data) < 36 + n_region * 40:
        raise ValueError(f"Invalid Wi-Fi RAM n_region={n_region}")
    offset = 0
    for i in range(n_region):
        reg_off = trailer_off - (n_region - i) * 40
        _dcrc, _dlen, _dblk = struct.unpack_from("<III", data, reg_off)
        addr, rlen, feature_set, rtype = struct.unpack_from("<IIBB", data, reg_off + 16)
        if offset + rlen > trailer_off - n_region * 40:
            raise ValueError(f"Wi-Fi RAM region {i} exceeds firmware bounds")
        offset += rlen
    return f"chip=0x{chip_id:02x} eco=0x{eco_code:02x} ver={fw_ver} build={build_date} regions={n_region}"


def validate_bt_ram(data: bytes) -> str:
    # btmtk_patch_header (32B) + btmtk_global_desc (64B) + section_num * 64B
    if len(data) < 96:
        raise ValueError(f"BT firmware too short ({len(data)} bytes)")
    build_date = data[0:16].decode("ascii", errors="replace").strip("\x00 ")
    platform = data[16:20].decode("ascii", errors="replace")
    hwver, swver = struct.unpack_from("<HH", data, 20)
    section_num = struct.unpack_from("<I", data, 32 + 12)[0]
    if section_num == 0 or len(data) < 96 + section_num * 64:
        raise ValueError(f"Invalid BT firmware section_num={section_num}")
    for i in range(section_num):
        off = 96 + i * 64
        _sectype, secoffset, _secsize = struct.unpack_from("<III", data, off)
        _dladdr, dlsize = struct.unpack_from("<II", data, off + 12)
        if dlsize > 0 and secoffset + dlsize > len(data):
            raise ValueError(
                f"BT section {i} out of bounds (offs={secoffset}, dlsize={dlsize})"
            )
    return f"platform={platform} hw=0x{hwver:04x} sw=0x{swver:04x} build={build_date} sections={section_num}"


def format_c_ident(name: str) -> str:
    return "kFw_" + name.replace(".", "_").replace("-", "_")


def emit_cpp(out_path: Path, table_sym: str, count_sym: str, header_inc: str, blobs: list[tuple[str, bytes]]) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Auto-generated by scripts/pack_firmware.py — DO NOT EDIT MANUALLY",
        "// SPDX-License-Identifier: GPL-2.0-only",
        f'#include "{header_inc}"',
        "",
        "namespace mt7902 {",
        "",
    ]

    entries = []
    for name, raw in blobs:
        comp = zlib.compress(raw, level=9)
        crc = zlib.crc32(raw) & 0xFFFFFFFF
        ident = format_c_ident(name)
        lines.append(
            f"// {name}: raw={len(raw)} bytes, zlib={len(comp)} bytes ({100.0 * len(comp) / len(raw):.1f}%), crc32=0x{crc:08x}"
        )
        lines.append(f"static const uint8_t {ident}[] = {{")
        for idx in range(0, len(comp), 16):
            chunk = comp[idx : idx + 16]
            hexes = ", ".join(f"0x{b:02X}" for b in chunk)
            lines.append(f"    {hexes},")
        lines.append("};")
        lines.append("")
        entries.append((name, ident, len(comp), len(raw), crc))

    lines.append(f"const EmbeddedFirmwareBlob {table_sym}[] = {{")
    for name, ident, csz, usz, crc in entries:
        lines.append(
            f'    {{ "{name}", {ident}, {csz}U, {usz}U, 0x{crc:08X}U }},'
        )
    lines.append("};")
    lines.append(f"const size_t {count_sym} = {len(entries)}U;")
    lines.append("")
    lines.append("} // namespace mt7902")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Pack MT7902 firmware into macOS kext C++ tables")
    parser.add_argument(
        "--fw-dir",
        type=Path,
        default=Path("/lib/firmware/mediatek"),
        help="Directory containing MediaTek MT7902 firmware (.bin or .bin.xz)",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="Repository root directory",
    )
    parser.add_argument(
        "--stub",
        action="store_true",
        help="Generate empty placeholder firmware tables (for CI without proprietary blobs)",
    )
    args = parser.parse_args()

    wifi_out = args.repo_root / "AirportMT7902" / "Firmware" / "MT7902WifiFwData.cpp"
    bt_out = args.repo_root / "MT7902BluetoothFirmware" / "Firmware" / "MT7902BtFwData.cpp"

    if args.stub:
        emit_cpp(wifi_out, "gWifiFirmwareTable", "gWifiFirmwareCount", "MT7902FwStore.hpp", [])
        emit_cpp(bt_out, "gBtFirmwareTable", "gBtFirmwareCount", "../../AirportMT7902/Firmware/MT7902FwStore.hpp", [])
        print("Generated empty stub firmware tables.")
        return 0

    wifi_patch = read_firmware_file(args.fw_dir, WIFI_PATCH_NAME)
    wifi_ram = read_firmware_file(args.fw_dir, WIFI_RAM_NAME)
    bt_ram = read_firmware_file(args.fw_dir, BT_RAM_NAME)

    print(f"[OK] {WIFI_PATCH_NAME}: {validate_wifi_patch(wifi_patch)}")
    print(f"[OK] {WIFI_RAM_NAME}: {validate_wifi_ram(wifi_ram)}")
    print(f"[OK] {BT_RAM_NAME}: {validate_bt_ram(bt_ram)}")

    emit_cpp(
        wifi_out,
        "gWifiFirmwareTable",
        "gWifiFirmwareCount",
        "MT7902FwStore.hpp",
        [(WIFI_PATCH_NAME, wifi_patch), (WIFI_RAM_NAME, wifi_ram)],
    )
    emit_cpp(
        bt_out,
        "gBtFirmwareTable",
        "gBtFirmwareCount",
        "../../AirportMT7902/Firmware/MT7902FwStore.hpp",
        [(BT_RAM_NAME, bt_ram)],
    )

    print(f"Wrote {wifi_out} ({wifi_out.stat().st_size} bytes)")
    print(f"Wrote {bt_out} ({bt_out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
