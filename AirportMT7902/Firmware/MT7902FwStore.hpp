static inline bool decompressZlib(const uint8_t *src, size_t srcLen,
                                  uint8_t *dst, size_t *dstLen) {
    if (!src || !dst || !dstLen || srcLen == 0 || *dstLen == 0)
        return false;

    z_stream stream;
    memset(&stream, 0, sizeof(stream));
    stream.next_in = const_cast<Bytef *>(reinterpret_cast<const Bytef *>(src));
    stream.avail_in = static_cast<uInt>(srcLen);
    stream.next_out = reinterpret_cast<Bytef *>(dst);
    stream.avail_out = static_cast<uInt>(*dstLen);
#ifdef KERNEL
    stream.zalloc = mt7902ZAlloc;
    stream.zfree = mt7902ZFree;
#else
    stream.zalloc = Z_NULL;
    stream.zfree = Z_NULL;
    stream.opaque = Z_NULL;
#endif

    int err = inflateInit(&stream);
    if (err != Z_OK)
        return false;

    err = inflate(&stream, Z_FINISH);
    if (err != Z_STREAM_END) {
        inflateEnd(&stream);
        return false;
    }

    *dstLen = static_cast<size_t>(stream.total_out);
    err = inflateEnd(&stream);
    return err == Z_OK;
}

static inline bool loadEmbeddedFirmware(const EmbeddedFirmwareBlob *table,
                                        size_t count,
                                        const char *name,
                                        FirmwareBuffer &out) {
    out.release();
    if (!table || !name)
        return false;

    for (size_t i = 0; i < count; ++i) {
        if (strcmp(table[i].name, name) != 0)
            continue;

        const auto &blob = table[i];
        if (!blob.compressedData || blob.compressedSize == 0 || blob.uncompressedSize == 0)
            return false;

        uint8_t *buf = static_cast<uint8_t *>(kallocZero(blob.uncompressedSize));
        if (!buf)
            return false;

        size_t actualLen = blob.uncompressedSize;
        if (!decompressZlib(blob.compressedData, blob.compressedSize, buf, &actualLen) ||
            actualLen != blob.uncompressedSize) {
            kfreeSized(buf, blob.uncompressedSize);
            return false;
        }

        out.data = buf;
        out.size = actualLen;
        return true;
    }
    return false;
}

