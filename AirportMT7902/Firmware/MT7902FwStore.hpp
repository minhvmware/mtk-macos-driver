#ifdef KERNEL
static inline voidpf mt7902ZAlloc(voidpf opaque, uInt items, uInt size) {
    (void)opaque;
    size_t total = static_cast<size_t>(items) * static_cast<size_t>(size) + sizeof(size_t);
    size_t *raw = static_cast<size_t *>(IOMalloc(total));
    if (!raw)
        return Z_NULL;
    *raw = total;
    return reinterpret_cast<voidpf>(raw + 1);
}

static inline void mt7902ZFree(voidpf opaque, voidpf address) {
    (void)opaque;
    if (!address)
        return;
    size_t *raw = static_cast<size_t *>(address) - 1;
    IOFree(raw, *raw);
}
#endif

struct EmbeddedFirmwareBlob {
    const char *name;
    const uint8_t *compressedData;
    size_t compressedSize;
    size_t uncompressedSize;
    uint32_t crc32;
};

struct FirmwareBuffer {
    uint8_t *data = nullptr;
    size_t size = 0;

    void release() {
        if (data) {
            kfreeSized(data, size);
            data = nullptr;
            size = 0;
        }
    }
};

